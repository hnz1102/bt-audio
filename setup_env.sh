#!/usr/bin/env bash
# setup_env.sh — Install all prerequisites for building and flashing the ESP32 Bluetooth A2DP sink (bt-audio).
# Target: Ubuntu / Debian (including WSL2)
# Target chip: original ESP32 (Xtensa); ESP-IDF v5.2.2 is fetched and built by esp-idf-sys on the first build.
set -euo pipefail

echo "=== [1/6] Installing system packages ==="
sudo apt update
sudo apt -y install \
    git python3 python3-pip python3-venv gcc build-essential curl \
    cmake ninja-build pkg-config libudev-dev clang libclang-dev \
    llvm-dev udev libssl-dev
# libtinfo5 is required by the Xtensa clang but is not available on newer releases.
sudo apt -y install libtinfo5 || echo "WARNING: libtinfo5 not available — install it manually if the build fails."

echo "=== [2/6] Installing Rust (rustup) ==="
if command -v rustup &>/dev/null; then
    echo "rustup already installed — skipping."
else
    curl --proto '=https' --tlsv1.2 -sSf https://sh.rustup.rs | sh -s -- -y
fi

# Make cargo/rustup available in this script session
# shellcheck source=/dev/null
source "$HOME/.cargo/env"

echo ""
echo "NOTE: Add the following line to your shell config (~/.bashrc, ~/.zshrc, etc.)"
echo "      if it is not already present:"
echo ""
echo '      source "$HOME/.cargo/env"'
echo ""

echo "=== [3/6] Installing Cargo tools ==="
cargo +stable install ldproxy
cargo +stable install espup
cargo +stable install cargo-espflash

echo "=== [4/6] Installing ESP32 (Xtensa) toolchain via espup ==="
espup install --targets esp32
espup update --targets esp32

echo "=== [5/6] Sourcing ESP environment ==="
# export-esp.sh is generated by espup in the home directory
EXPORT_ESP="$HOME/export-esp.sh"
if [[ -f "$EXPORT_ESP" ]]; then
    # shellcheck source=/dev/null
    source "$EXPORT_ESP"
    echo "Sourced $EXPORT_ESP"
else
    echo "WARNING: $EXPORT_ESP not found. Run '. ~/export-esp.sh' manually."
fi

echo "=== [6/6] Granting serial port access (dialout group) ==="
# ESP32 dev boards use a USB-UART bridge (CP210x, CH340, FTDI) that appears as /dev/ttyUSB*.
if id -nG "$USER" | grep -qw dialout; then
    echo "$USER is already in the dialout group."
else
    sudo usermod -aG dialout "$USER"
    echo "Added $USER to the dialout group — log out and back in for it to take effect."
fi

echo ""
echo "=== Setup complete ==="
echo "Open a new terminal (or run 'source \"\$HOME/.cargo/env\" && source ~/export-esp.sh')"
echo "then build and flash with:"
echo "  cargo build --release"
echo "  cargo espflash flash --release --monitor --port /dev/ttyUSB0"
